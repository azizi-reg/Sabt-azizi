def find_image():
    # بررسی تمام نام‌ها و فرمت‌های محتمل در مخزن
    possible_names = [
        "جدید با لباس سفید.jpg",
        "جدید با لباس سفید.png",
        "جدید با لباس سفید.jpeg",
        "profile.jpg",
        "profile.png",
        "profile.jpeg",
        "image.jpg",
        "image.png"
    ]
    
    # ابتدا در لیست مشخص
    for name in possible_names:
        if os.path.exists(name):
            return name
            
    # در صورت تفاوت در حروف بزرگ و کوچک، کل پوشه را اسکن می‌کند
    for file in os.listdir("."):
        if file.lower().endswith(('.png', '.jpg', '.jpeg')) and not file.startswith('.'):
            return file
            
    return None

found_img = find_image()

